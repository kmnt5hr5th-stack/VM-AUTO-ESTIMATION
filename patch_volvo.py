def empty():
    return {"essence":[],"diesel":[],"hybride":[],"electrique":[],"gpl":[]}

FUEL_KEYS = ['essence','diesel','hybride','electrique','gpl']

def add(model, year, v, fuel):
    if year not in model:
        model[year] = empty()
    if isinstance(model[year], dict) and fuel in model[year]:
        if v not in model[year][fuel]:
            model[year][fuel].append(v)

def clean_parasites(model):
    for k in FUEL_KEYS:
        model.pop(k, None)

def clean_1(s):
    s = s.strip()
    return re.sub(r'^\(\d+\)\s+', '', s).strip()

def fuel_xc60_1(v):
    u = v.upper()
    if any(x in u for x in ['D3', 'D4', 'D5', '2.4 D']):
        return 'diesel'
    return 'essence'

def clean_2(s):
    s = s.strip()
    prev = None
    while prev != s:
        prev = s
        s = re.sub(r'^II\s+', '', s).strip()
        s = re.sub(r'^\(\d+\)\s+', '', s).strip()
    return s

def fuel_xc60_2(v):
    u = v.upper()
    if 'DIESEL' in u: return 'diesel'
    if u.startswith('D3 ') or u.startswith('D4 ') or u.startswith('D5 '): return 'diesel'
    if ' D3 ' in u or ' D4 ' in u or ' D5 ' in u: return 'diesel'
    if '2.0 D' in u: return 'diesel'
    if 'B5 D' in u or 'B4 D' in u or 'DAWD' in u: return 'diesel'
    if 'ADBLUE' in u and any(x in u for x in ['D3', 'D4', 'D5']): return 'diesel'
    if 'T8' in u or 'RECHARGE' in u or 'TWIN ENGINE' in u: return 'hybride'
    if 'B5 H' in u: return 'hybride'
    return 'essence'

